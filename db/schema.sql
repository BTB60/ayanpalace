ALTER TABLE staff ADD COLUMN IF NOT EXISTS can_categories BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE staff ADD COLUMN IF NOT EXISTS can_qr BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE staff ADD COLUMN IF NOT EXISTS can_billing BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS settings (
  id BIGSERIAL PRIMARY KEY,
  key_name TEXT NOT NULL DEFAULT '',
  value TEXT NOT NULL DEFAULT ''
);
